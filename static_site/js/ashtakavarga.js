/* =============================================================================
 *  ashtakavarga.js — Бхиннаштакаварга (БАВ) + Сарваштакаварга (САВ). window.LunAV
 * =============================================================================
 *  Таблицы бинду выгружены из kunjara/jyotish (следует BPHS) и сверены
 *  контрольными суммами: Со48 Лу49 Ма39 Ме54 Юп56 Ве52 Са39, сумма = 337.
 *  Дома в таблицах отсчитываются ВКЛЮЧИТЕЛЬНО от знака донора.
 * ===========================================================================*/
(function () {
  // доноры и планеты: Su Mo Ma Me Ju Ve Sa (+ Lg как донор)
  var DON = ['Su', 'Mo', 'Ma', 'Me', 'Ju', 'Ve', 'Sa', 'Lg'];
  var PL = ['Su', 'Mo', 'Ma', 'Me', 'Ju', 'Ve', 'Sa'];

  // T[planet][donor] = массив домов (1..12) от донора, где планета получает бинду
  var T = {
    Su: { Su: [1, 2, 4, 7, 8, 9, 10, 11], Mo: [3, 6, 10, 11], Ma: [1, 2, 4, 7, 8, 9, 10, 11], Me: [3, 5, 6, 9, 10, 11, 12], Ju: [5, 6, 9, 11], Ve: [6, 7, 12], Sa: [1, 2, 4, 7, 8, 9, 10, 11], Lg: [3, 4, 6, 10, 11, 12] },
    Mo: { Su: [3, 6, 7, 8, 10, 11], Mo: [1, 3, 6, 7, 9, 10, 11], Ma: [2, 3, 5, 6, 10, 11], Me: [1, 3, 4, 5, 7, 8, 10, 11], Ju: [1, 2, 4, 7, 8, 10, 11], Ve: [3, 4, 5, 7, 9, 10, 11], Sa: [3, 5, 6, 11], Lg: [3, 6, 10, 11] },
    Ma: { Su: [3, 5, 6, 10, 11], Mo: [3, 6, 11], Ma: [1, 2, 4, 7, 8, 10, 11], Me: [3, 5, 6, 11], Ju: [6, 10, 11, 12], Ve: [6, 8, 11, 12], Sa: [1, 4, 7, 8, 9, 10, 11], Lg: [1, 3, 6, 10, 11] },
    Me: { Su: [5, 6, 9, 11, 12], Mo: [2, 4, 6, 8, 10, 11], Ma: [1, 2, 4, 7, 8, 9, 10, 11], Me: [1, 3, 5, 6, 9, 10, 11, 12], Ju: [6, 8, 11, 12], Ve: [1, 2, 3, 4, 5, 8, 9, 11], Sa: [1, 2, 4, 7, 8, 9, 10, 11], Lg: [1, 2, 4, 6, 8, 10, 11] },
    Ju: { Su: [1, 2, 3, 4, 7, 8, 9, 10, 11], Mo: [2, 5, 7, 9, 11], Ma: [1, 2, 4, 7, 8, 10, 11], Me: [1, 2, 4, 5, 6, 9, 10, 11], Ju: [1, 2, 3, 4, 7, 8, 10, 11], Ve: [2, 5, 6, 9, 10, 11], Sa: [3, 5, 6, 12], Lg: [1, 2, 4, 5, 6, 7, 9, 10, 11] },
    Ve: { Su: [8, 11, 12], Mo: [1, 2, 3, 4, 5, 8, 9, 11, 12], Ma: [3, 4, 6, 9, 11, 12], Me: [3, 5, 6, 9, 11], Ju: [5, 8, 9, 10, 11], Ve: [1, 2, 3, 4, 5, 8, 9, 10, 11], Sa: [3, 4, 5, 8, 9, 10, 11], Lg: [1, 2, 3, 4, 5, 8, 9, 11] },
    Sa: { Su: [1, 2, 4, 7, 8, 10, 11], Mo: [3, 6, 11], Ma: [3, 5, 6, 10, 11, 12], Me: [6, 8, 9, 10, 11, 12], Ju: [5, 6, 11, 12], Ve: [6, 11, 12], Sa: [3, 5, 6, 11], Lg: [1, 3, 4, 6, 10, 11] },
  };
  var TOTALS = { Su: 48, Mo: 49, Ma: 39, Me: 54, Ju: 56, Ve: 52, Sa: 39 };

  // signs: { Su:1..12, Mo:.., ..., Sa:.., Lg:1..12 } — знаки D1 планет и лагны
  // -> { bav: {Su:[12],...}, sav:[12], bavTotals:{...}, savTotal }
  function compute(signs) {
    var bav = {}, sav = new Array(12).fill(0), bavTotals = {};
    PL.forEach(function (p) {
      var arr = new Array(12).fill(0);
      DON.forEach(function (c) {
        var cs = signs[c]; if (!cs) return;              // знак донора 1..12
        var houses = T[p][c];
        houses.forEach(function (h) {
          var idx = ((cs - 1) + (h - 1)) % 12;           // знак, получающий бинду (0..11)
          arr[idx] += 1;
        });
      });
      bav[p] = arr;
      var tot = arr.reduce(function (a, b) { return a + b; }, 0);
      bavTotals[p] = tot;
      for (var i = 0; i < 12; i++) sav[i] += arr[i];     // САВ — сумма 7 планет (без Лагны)
    });
    var savTotal = sav.reduce(function (a, b) { return a + b; }, 0);
    return { bav: bav, sav: sav, bavTotals: bavTotals, savTotal: savTotal, planets: PL };
  }

  window.LunAV = { compute: compute, TOTALS: TOTALS, tables: T, planets: PL, donors: DON };
})();
